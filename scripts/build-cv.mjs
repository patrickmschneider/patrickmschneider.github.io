import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse } from 'yaml';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const cvDirectory = join(root, 'cv');
const source = join(cvDirectory, 'cv.tex');
const buildDirectory = join(cvDirectory, 'build');
const generatedDirectory = join(cvDirectory, 'generated');
const builtPdf = join(buildDirectory, 'cv.pdf');
const publishedPdf = join(root, 'public', 'files', 'cv.pdf');

if (!existsSync(source)) {
  throw new Error('CV source not found at cv/cv.tex');
}

mkdirSync(buildDirectory, { recursive: true });
mkdirSync(generatedDirectory, { recursive: true });

const readYaml = (name) => parse(readFileSync(join(root, 'src', 'data', name), 'utf8'));

function texEscape(value) {
  return String(value)
    .replace(/\\/g, '\\textbackslash{}')
    .replace(/([&%$#_{}])/g, '\\$1')
    .replace(/~/g, '\\textasciitilde{}')
    .replace(/\^/g, '\\textasciicircum{}');
}

function writeGenerated(name, content) {
  const path = join(generatedDirectory, name);
  const next = `${content.trim()}\n`;
  if (!existsSync(path) || readFileSync(path, 'utf8') !== next) writeFileSync(path, next);
}

const profile = readYaml('profile.yaml');
const requiredProfileFields = [
  'name',
  'position',
  'position_start',
  'affiliation',
  'department',
  'address',
  'email',
];
for (const field of requiredProfileFields) {
  if (profile[field] === undefined || profile[field] === '') {
    throw new Error(`Missing ${field} in src/data/profile.yaml`);
  }
}

writeGenerated(
  'profile.tex',
  [
    '% Generated by scripts/build-cv.mjs from src/data/profile.yaml.',
    `\\newcommand{\\CVName}{${texEscape(profile.name)}}`,
    `\\newcommand{\\CVPosition}{${texEscape(profile.position)}}`,
    `\\newcommand{\\CVPositionStart}{${texEscape(profile.position_start)}}`,
    `\\newcommand{\\CVAffiliation}{${texEscape(profile.affiliation)}}`,
    `\\newcommand{\\CVDepartment}{${texEscape(profile.department)}}`,
    `\\newcommand{\\CVAddress}{${texEscape(profile.address)}}`,
    `\\newcommand{\\CVEmail}{${texEscape(profile.email)}}`,
  ].join('\n'),
);

const papers = readYaml('papers.yaml');
if (!Array.isArray(papers)) throw new Error('src/data/papers.yaml must contain a list');

const authorName = (author) => (typeof author === 'string' ? author : author.name);
function authorLine(coauthors = []) {
  const names = coauthors.map(authorName);
  if (names.length === 0) return '';
  if (names.length > 4) return `, with ${texEscape(names[0])} and others`;
  if (names.length === 1) return `, with ${texEscape(names[0])}`;
  return `, with ${names.slice(0, -1).map(texEscape).join(', ')} and ${texEscape(names.at(-1))}`;
}

function venueLine(venue) {
  if (!venue) return '';
  return ` \\newline \\textit{${texEscape(venue.replaceAll('*', ''))}}`;
}

function sectionRows(section, heading) {
  const selected = papers
    .map((paper, index) => ({ ...paper, index }))
    .filter((paper) => paper.section === section)
    .sort((a, b) => (b.year ?? 0) - (a.year ?? 0) || a.index - b.index);
  if (selected.length === 0) return '';

  const rows = selected.map((paper, index) => {
    if (!paper.title || !paper.year) throw new Error(`A ${section} paper is missing its title or year`);
    const spacing = index === selected.length - 1 ? '\\xxxxx' : '\\\\';
    return `& ${texEscape(paper.year)} & \`\`${texEscape(paper.title)}''${authorLine(paper.coauthors)}${venueLine(paper.venue)}${spacing}`;
  });
  return [`\\multicolumn{3}{l}{\\textbf{${heading}}} \\\\ \\hline`, ...rows].join('\n');
}

writeGenerated(
  'research.tex',
  [
    '% Generated by scripts/build-cv.mjs from src/data/papers.yaml.',
    '\\newcommand{\\CVResearch}{%',
    sectionRows('published', 'Publications'),
    sectionRows('working', 'Working Papers'),
    sectionRows('prephd', 'Policy Notes \\& Pre--PhD Publications'),
    '}',
  ]
    .filter(Boolean)
    // Blank paragraphs are not valid inside the surrounding tabularx.
    .join('\n'),
);

const result = spawnSync(
  'latexmk',
  [
    '-pdf',
    '-interaction=nonstopmode',
    '-halt-on-error',
    '-file-line-error',
    '-outdir=build',
    'cv.tex',
  ],
  { cwd: cvDirectory, stdio: 'inherit' },
);

if (result.error?.code === 'ENOENT') {
  throw new Error('latexmk is not installed or is not available on PATH');
}
if (result.error) throw result.error;
if (result.status !== 0) process.exit(result.status ?? 1);
if (!existsSync(builtPdf)) {
  throw new Error('LaTeX completed without producing cv/build/cv.pdf');
}

mkdirSync(dirname(publishedPdf), { recursive: true });
copyFileSync(builtPdf, publishedPdf);
console.log('Published cv/build/cv.pdf to public/files/cv.pdf');
